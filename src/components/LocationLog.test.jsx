import {cleanup,fireEvent,render,screen} from '@testing-library/react';
import {afterEach,beforeEach,expect,it,vi} from 'vitest';
const mocks=vi.hoisted(()=>({diagnosticLogArchive:vi.fn()}));
vi.mock('../lib/recorder.js',()=>({recorder:mocks,recorderAvailable:()=>true}));
const sent=vi.hoisted(()=>({send:vi.fn()}));
vi.mock('../lib/supabase.js',()=>({supabase:{}}));
vi.mock('../lib/AuthContext.jsx',()=>({useAuth:()=>({status:'authenticated'})}));
vi.mock('../lib/feedback.js',async original=>({...(await original()),sendReportAsFeedback:sent.send}));
import LocationLog from './LocationLog.jsx';
beforeEach(()=>{mocks.diagnosticLogArchive.mockReset();sent.send.mockReset();});
afterEach(()=>{cleanup();});
it('sends the compressed diagnostic log as feedback: no share sheet, no copy',async()=>{
 mocks.diagnosticLogArchive.mockResolvedValue({fileName:'log.json.gz',base64:btoa('\x1f\x8bdata'),events:6000});
 sent.send.mockResolvedValue({id:'t',number:12});
 render(<LocationLog/>);
 expect(screen.getAllByRole('button').map(button=>button.textContent)).toEqual([' Send diagnostic log as feedback']);
 fireEvent.click(screen.getByRole('button',{name:/Send diagnostic log as feedback/}));
 expect(await screen.findByRole('status')).toHaveTextContent('Sent as feedback #12');
 const args=sent.send.mock.calls[0][1];
 expect(args.kind).toBe('diagnosticLog');expect(args.blob.type).toBe('application/gzip');
 expect(new Uint8Array(await args.blob.arrayBuffer()).slice(0,2)).toEqual(new Uint8Array([0x1f,0x8b]));
});
it('shows a failure and lets the same log be sent again',async()=>{
 mocks.diagnosticLogArchive.mockRejectedValueOnce(new Error('The diagnostic log could not be created. Nothing was exported.')).mockResolvedValueOnce({base64:btoa('x')});
 sent.send.mockResolvedValue({id:'t',number:3});
 render(<LocationLog/>);fireEvent.click(screen.getByRole('button',{name:/as feedback/}));
 expect(await screen.findByRole('alert')).toHaveTextContent('could not be created');
 expect(sent.send).not.toHaveBeenCalled();
 fireEvent.click(screen.getByRole('button',{name:/as feedback/}));
 expect(await screen.findByRole('status')).toHaveTextContent('#3');
});
