-- Feedback: ticket numbers, app admins, reports attached to tickets, and file
-- removal when a ticket is closed.
--
-- * Every ticket gets a short number (#42) a person can quote.
-- * Admins are listed in public.app_admins, which only SQL (service role) can
--   change. Admins read every ticket, its conversation and its files, reply as
--   staff, set the status and hide (soft-delete) tickets. Make someone an admin:
--     insert into public.app_admins(user_id)
--     select id from auth.users where email = 'person@example.com'
--     on conflict do nothing;
--   Remove: delete from public.app_admins where user_id = (select id from auth.users where email = 'person@example.com');
-- * Reports (recording, journey and tracking reports as text, and the
--   compressed diagnostic log) are stored with a ticket in the existing private
--   bucket, under the same owner/ticket folder as photos, so account deletion
--   already removes them. At most three per ticket.
-- * Closing a ticket removes its photos and reports: the rows go here and the
--   function returns their storage keys for the admin's app to delete (Storage
--   objects cannot be deleted with SQL). The ticket text and conversation stay.
--
-- Safe to re-run. Forward-only: nothing already applied is edited.
begin;

alter table public.feedback add column if not exists number bigint generated by default as identity;
create unique index if not exists feedback_number_unique on public.feedback(number);
alter table public.feedback add column if not exists deleted_at timestamptz;
alter table public.feedback add column if not exists files_removed_at timestamptz;

create table if not exists public.app_admins (
 user_id uuid primary key references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
alter table public.app_admins enable row level security;
revoke all on public.app_admins from public,anon,authenticated;
grant all on public.app_admins to service_role;

create or replace function public.is_app_admin() returns boolean
language sql stable security definer set search_path='' as $$
 select auth.uid() is not null and public.account_is_active()
  and exists(select 1 from public.app_admins a where a.user_id=auth.uid())
$$;
revoke all on function public.is_app_admin() from public,anon,authenticated;
grant execute on function public.is_app_admin() to authenticated;

-- A hidden ticket disappears for its owner; admins still see it.
drop policy if exists feedback_owner_read on public.feedback;
create policy feedback_owner_read on public.feedback for select to authenticated
 using(owner_id=(select auth.uid()) and deleted_at is null);
drop policy if exists feedback_admin_read on public.feedback;
create policy feedback_admin_read on public.feedback for select to authenticated
 using((select public.is_app_admin()));
drop policy if exists feedback_messages_admin_read on public.feedback_messages;
create policy feedback_messages_admin_read on public.feedback_messages for select to authenticated
 using((select public.is_app_admin()));
drop policy if exists feedback_attachments_admin_read on public.feedback_attachments;
create policy feedback_attachments_admin_read on public.feedback_attachments for select to authenticated
 using((select public.is_app_admin()));

create table if not exists public.feedback_reports (
 -- The client chooses the ID so a retried upload writes the same object key.
 id uuid primary key,
 feedback_id uuid not null references public.feedback(id) on delete cascade,
 owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 kind text not null check(kind in ('recording','journey','tracking','diagnosticLog')),
 title text not null default '' check(length(title)<=120),
 object_key text not null unique,
 mime_type text not null check(mime_type in ('text/plain','application/gzip')),
 byte_size integer not null check(byte_size between 1 and 10485760),
 created_at timestamptz not null default now(),
 check(object_key=owner_id::text||'/'||feedback_id::text||'/'||id::text||case when mime_type='text/plain' then '.txt' else '.json.gz' end)
);
create index if not exists feedback_reports_ticket on public.feedback_reports(feedback_id);

create or replace function public.enforce_feedback_report_limit() returns trigger
language plpgsql set search_path='' as $$
begin
 perform pg_advisory_xact_lock(hashtextextended('feedback-reports:'||new.feedback_id::text,0));
 if (select count(*) from public.feedback_reports where feedback_id=new.feedback_id and id<>new.id)>=3 then
  raise exception 'A feedback ticket can have up to 3 reports.' using errcode='22023';
 end if;
 return new;
end $$;
drop trigger if exists feedback_report_limit on public.feedback_reports;
create trigger feedback_report_limit before insert or update on public.feedback_reports
 for each row execute function public.enforce_feedback_report_limit();

alter table public.feedback_reports enable row level security;
revoke all on public.feedback_reports from public,anon,authenticated;
grant select,insert,update on public.feedback_reports to authenticated;
grant all on public.feedback_reports to service_role;
drop policy if exists feedback_reports_owner_read on public.feedback_reports;
create policy feedback_reports_owner_read on public.feedback_reports for select to authenticated
 using(owner_id=(select auth.uid()));
drop policy if exists feedback_reports_admin_read on public.feedback_reports;
create policy feedback_reports_admin_read on public.feedback_reports for select to authenticated
 using((select public.is_app_admin()));
drop policy if exists feedback_reports_owner_insert on public.feedback_reports;
create policy feedback_reports_owner_insert on public.feedback_reports for insert to authenticated
 with check(owner_id=(select auth.uid()) and exists(
  select 1 from public.feedback f where f.id=feedback_id and f.owner_id=(select auth.uid()) and f.status<>'closed'));
-- A retried upload upserts the same row.
drop policy if exists feedback_reports_owner_update on public.feedback_reports;
create policy feedback_reports_owner_update on public.feedback_reports for update to authenticated
 using(owner_id=(select auth.uid()))
 with check(owner_id=(select auth.uid()) and exists(
  select 1 from public.feedback f where f.id=feedback_id and f.owner_id=(select auth.uid()) and f.status<>'closed'));
drop policy if exists account_active on public.feedback_reports;
create policy account_active on public.feedback_reports as restrictive for all to authenticated
 using((select public.account_is_active())) with check((select public.account_is_active()));

-- Objects: photos (<uuid>.jpg, up to 5) and reports (<uuid>.txt or .json.gz, up to 3)
-- in the owner's folder for one of their open tickets.
create or replace function public.can_write_feedback_object(p_name text)
returns boolean language plpgsql volatile security definer set search_path='' as $$
declare parts text[]:=string_to_array(p_name,'/');
 uuid_pattern constant text:='[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}';
 photo boolean;
begin
 if auth.uid() is null or not public.account_is_active() then return false; end if;
 if coalesce(array_length(parts,1),0)<>3 or parts[1]<>auth.uid()::text
  or parts[2] !~ ('^'||uuid_pattern||'$') or parts[3] !~ ('^'||uuid_pattern||'\.(jpg|txt|json\.gz)$') then return false; end if;
 if not exists(select 1 from public.feedback f where f.id=parts[2]::uuid and f.owner_id=auth.uid() and f.status<>'closed') then return false; end if;
 photo:=parts[3] like '%.jpg';
 -- Taken only for the caller's own open ticket, so nobody can wait on another's lock.
 perform pg_advisory_xact_lock(hashtextextended((case when photo then 'feedback-photos:' else 'feedback-reports:' end)||parts[2],0));
 return (select count(*) from storage.objects o
  where o.bucket_id='feedback-attachments' and o.name like parts[1]||'/'||parts[2]||'/%' and o.name<>p_name
   and (o.name like '%.jpg')=photo)<(case when photo then 5 else 3 end);
end $$;

-- An object can be removed only while nothing refers to it.
create or replace function public.can_delete_feedback_object(p_name text)
returns boolean language sql stable security definer set search_path='' as $$
 select auth.uid() is not null and public.account_is_active()
  and split_part(p_name,'/',1)=auth.uid()::text
  and not exists(select 1 from public.feedback_attachments a where a.object_key=p_name)
  and not exists(select 1 from public.feedback_reports r where r.object_key=p_name)
$$;

-- An admin removes the files of a closed ticket once its rows are gone.
create or replace function public.can_admin_remove_feedback_object(p_name text)
returns boolean language plpgsql stable security definer set search_path='' as $$
declare ticket text:=split_part(p_name,'/',2);
begin
 if not public.is_app_admin() or ticket !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then return false; end if;
 return exists(select 1 from public.feedback f where f.id=ticket::uuid and f.status='closed')
  and not exists(select 1 from public.feedback_attachments a where a.object_key=p_name)
  and not exists(select 1 from public.feedback_reports r where r.object_key=p_name);
end $$;
revoke all on function public.can_admin_remove_feedback_object(text) from public,anon,authenticated;
grant execute on function public.can_admin_remove_feedback_object(text) to authenticated;

do $$
begin
 if exists(select 1 from information_schema.schemata where schema_name='storage') then
  update storage.buckets set public=false,file_size_limit=10485760,allowed_mime_types=array['image/jpeg','text/plain','application/gzip']
   where id='feedback-attachments';
  drop policy if exists "feedback attachments admin read" on storage.objects;
  create policy "feedback attachments admin read" on storage.objects for select to authenticated
   using(bucket_id='feedback-attachments' and (select public.is_app_admin()));
  drop policy if exists "feedback attachments admin delete" on storage.objects;
  create policy "feedback attachments admin delete" on storage.objects for delete to authenticated
   using(bucket_id='feedback-attachments' and public.can_admin_remove_feedback_object(name));
 end if;
end $$;

create or replace function public.admin_reply_feedback(p_feedback_id uuid,p_body text) returns uuid
language plpgsql security definer set search_path='' as $$
declare message_id uuid; body text:=btrim(coalesce(p_body,''));
begin
 if not public.is_app_admin() then raise exception 'Only an admin can reply as staff.' using errcode='42501'; end if;
 if body='' or length(body)>4000 then raise exception 'Write a reply of 4,000 characters or fewer.' using errcode='22023'; end if;
 if not exists(select 1 from public.feedback where id=p_feedback_id) then raise exception 'Feedback not found.' using errcode='22023'; end if;
 insert into public.feedback_messages(feedback_id,author_id,is_staff,body) values(p_feedback_id,auth.uid(),true,body) returning id into message_id;
 update public.feedback set status=case when status='open' then 'in_review' else status end,updated_at=now() where id=p_feedback_id;
 return message_id;
end $$;

-- Returns the storage keys of files removed by closing, for the caller to delete.
create or replace function public.admin_set_feedback_status(p_feedback_id uuid,p_status text) returns text[]
language plpgsql security definer set search_path='' as $$
declare keys text[]:='{}';
begin
 if not public.is_app_admin() then raise exception 'Only an admin can change the status.' using errcode='42501'; end if;
 if p_status is null or p_status not in ('open','in_review','resolved','closed') then raise exception 'Choose a valid status.' using errcode='22023'; end if;
 update public.feedback set status=p_status,updated_at=now() where id=p_feedback_id;
 if not found then raise exception 'Feedback not found.' using errcode='22023'; end if;
 if p_status='closed' then
  select coalesce(array_agg(object_key),'{}') into keys from (
   select object_key from public.feedback_attachments where feedback_id=p_feedback_id
   union all select object_key from public.feedback_reports where feedback_id=p_feedback_id) files;
  delete from public.feedback_attachments where feedback_id=p_feedback_id;
  delete from public.feedback_reports where feedback_id=p_feedback_id;
  if cardinality(keys)>0 then update public.feedback set files_removed_at=now() where id=p_feedback_id; end if;
 end if;
 return keys;
end $$;

create or replace function public.admin_set_feedback_deleted(p_feedback_id uuid,p_deleted boolean) returns void
language plpgsql security definer set search_path='' as $$
begin
 if not public.is_app_admin() then raise exception 'Only an admin can hide feedback.' using errcode='42501'; end if;
 update public.feedback set deleted_at=case when p_deleted then coalesce(deleted_at,now()) end,updated_at=now() where id=p_feedback_id;
 if not found then raise exception 'Feedback not found.' using errcode='22023'; end if;
end $$;

create or replace function public.admin_feedback_authors(p_ids uuid[]) returns table(id uuid,display_name text)
language plpgsql stable security definer set search_path='' as $$
begin
 if not public.is_app_admin() then raise exception 'Only an admin can see who sent feedback.' using errcode='42501'; end if;
 return query select p.id,p.display_name from public.profiles p where p.id=any(p_ids);
end $$;

revoke all on function public.admin_reply_feedback(uuid,text),public.admin_set_feedback_status(uuid,text),
 public.admin_set_feedback_deleted(uuid,boolean),public.admin_feedback_authors(uuid[]) from public,anon,authenticated;
grant execute on function public.admin_reply_feedback(uuid,text),public.admin_set_feedback_status(uuid,text),
 public.admin_set_feedback_deleted(uuid,boolean),public.admin_feedback_authors(uuid[]) to authenticated;

commit;
